import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const catalogs = JSON.parse(fs.readFileSync(path.join(root, 'src/localization/catalog.json'), 'utf8'));
const narrow = [], wide = [];
const narrowOffsets = new Map(), wideOffsets = new Map();
function intern(text, kind) {
    if (typeof text !== 'string' || text.includes('\0')) throw new Error('Invalid catalog string');
    const pool = kind === 'utf8' ? narrow : wide;
    const offsets = kind === 'utf8' ? narrowOffsets : wideOffsets;
    if (offsets.has(text)) return offsets.get(text);
    const offset = pool.length;
    const values = kind === 'utf8' ? Buffer.from(text, 'utf8')
        : Array.from({ length: text.length }, (_, i) => text.charCodeAt(i));
    for (const value of values) pool.push(value);
    pool.push(0);
    offsets.set(text, offset);
    return offset;
}
const declarations = [];
for (const catalog of catalogs) {
    if (!/^[A-Za-z]+$/.test(catalog.name)) throw new Error('Invalid catalog name');
    const fields = catalog.fields;
    declarations.push(`struct ${catalog.name}Entry {`);
    for (const field of fields) {
        if (!/^[a-z]+$/.test(field.name) || !['utf8', 'utf16'].includes(field.kind)) throw new Error('Invalid catalog field');
        declarations.push(`    ${field.kind === 'utf8' ? 'NarrowText' : 'WideText'} ${field.name};`);
    }
    declarations.push('};', `inline constexpr ${catalog.name}Entry ${catalog.name}[] = {`);
    for (const row of catalog.entries) {
        if (row.length !== fields.length) throw new Error(`Field count mismatch: ${catalog.name}`);
        declarations.push('    {' + row.map((text, i) => `{${intern(text, fields[i].kind)}}`).join(', ') + '},');
    }
    declarations.push('};');
}
function emitPool(name, type, values) {
    const lines = [`inline constexpr ${type} ${name}[] = {`];
    for (let i = 0; i < values.length; i += 24)
        lines.push('    ' + values.slice(i, i + 24).map(v => '0x' + v.toString(16)).join(', ') + ',');
    lines.push('};');
    return lines.join('\n');
}
const output = [
    '// Generated by scripts/generate_catalog.mjs from catalog.json; do not edit offsets manually.',
    '#pragma once', '#include <cstdint>', '', 'namespace attendance::catalog {',
    emitPool('narrowPool', 'char', narrow.map(v => v < 128 ? v : v - 256)).replace(/0x-([0-9a-f]+)/g, '-0x$1'),
    emitPool('widePool', 'wchar_t', wide),
    'struct NarrowText { std::uint32_t offset; constexpr const char* get() const { return narrowPool + offset; } };',
    'struct WideText { std::uint32_t offset; constexpr const wchar_t* get() const { return widePool + offset; } };',
    ...declarations, '} // namespace attendance::catalog', ''
].join('\n');
const target = path.join(root, 'src/localization/catalog_data.h');
const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
if (process.argv.includes('--check')) {
    if (current !== output) throw new Error('Catalog data is stale; regenerate it before building');
} else if (current !== output) {
    fs.writeFileSync(target, output);
}
console.log(`Generated ${catalogs.length} catalogs: ${narrow.length} UTF-8 bytes, ${wide.length} UTF-16 units.`);
