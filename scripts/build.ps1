param([switch]$Tests,[switch]$Analyze,[switch]$Direct)
. (Join-Path $PSScriptRoot 'storage.ps1')
$build=Join-Path $script:ProjectRoot 'build';[void][IO.Directory]::CreateDirectory($build)
$before=Get-TreeSnapshot $build;$peak=$before.Bytes
try {
 if((Get-GeneratedBytes) -ge 512MB){& (Join-Path $PSScriptRoot 'clean.ps1') -Mode Intermediates -Execute}
 if(-not $Direct -and (Get-Command cmake.exe -ErrorAction SilentlyContinue)){
  $testing=if($Tests){'ON'}else{'OFF'}
  $peak=[Math]::Max($peak,(Invoke-BoundedProcess cmake.exe @('-S',$script:ProjectRoot,'-B',$build,'-A','x64',('-DBUILD_TESTING='+$testing)) (Join-Path $build 'configure')))
  $target=if($Tests){'AttendanceApp','AttendanceTests'}else{,'AttendanceApp'}
  $arguments=@('--build',$build,'--config','Release','--target')+$target+@('--parallel','2')
  if($Analyze){$arguments+=@('--','/p:RunCodeAnalysis=true','/p:EnableMicrosoftCodeAnalysis=true')}
  $peak=[Math]::Max($peak,(Invoke-BoundedProcess cmake.exe $arguments (Join-Path $build 'compile')))
 }else{
  if($Tests -or $Analyze){throw 'CMake is required for tests and static analysis.'}
  $peak=[Math]::Max($peak,(Invoke-BoundedProcess powershell.exe @('-NoProfile','-ExecutionPolicy','Bypass','-File',(Join-Path $PSScriptRoot 'build_msvc.ps1')) (Join-Path $build 'compile')))
 }
 $after=Get-TreeSnapshot $build
 [pscustomobject]@{Before=$before;After=$after;SampledPeakBytes=$peak;BudgetBytes=512MB}|ConvertTo-Json -Depth 6|Set-Content -LiteralPath (Join-Path $build 'storage-summary.json') -Encoding UTF8
 Write-Output "Build complete. Generated bytes: $($after.Bytes); sampled peak: $peak."
}catch{if((Get-GeneratedBytes) -ge 512MB){& (Join-Path $PSScriptRoot 'clean.ps1') -Mode Intermediates -Execute};throw}
